class Mentio:
    """The Mentio API: one object, one call per endpoint, grouped by resource.

    client = Mentio(api_key)
    mentions = client.mentions.search(platform="reddit", relevant=True)

    Every call returns the parsed response (the generated model, a str for CSV
    exports, None for a 204) or raises MentioError with the API's status, code
    and message. Enum-valued arguments take plain strings, instants take a
    datetime, an ISO 8601 string or epoch milliseconds, bodies take a dict, a
    model, or their fields as keyword arguments. `client` is the underlying
    AuthenticatedClient for anything the facade does not cover.
    """

    def __init__(
        self,
        api_key: str,
        *,
        base_url: str = DEFAULT_BASE_URL,
        timeout: float | None = 30.0,
        headers: dict[str, str] | None = None,
        httpx_args: dict[str, Any] | None = None,
    ) -> None:
        self.client = AuthenticatedClient(
            base_url=base_url.rstrip("/"),
            token=api_key,
            prefix="Bearer",
            headers=headers or {},
            timeout=httpx.Timeout(timeout) if timeout is not None else None,
            httpx_args=httpx_args or {},
        )
        self.keywords = _Keywords(self.client)
        self.mentions = _Mentions(self.client)
        self.people = _People(self.client)
        self.segments = _Segments(self.client)
        self.alerts = _Alerts(self.client)
        self.channels = _Channels(self.client)
        self.company = _Company(self.client)
        self.analytics = _Analytics(self.client)
        self.api_keys = _ApiKeys(self.client)
        self.system = _System(self.client)
        self.filters = _Filters(self.client)
        self.auth = _Auth(self.client)
        self.members = _Members(self.client)
        self.usage = _Usage(self.client)

    def __enter__(self) -> "Mentio":
        self.client.__enter__()
        return self

    def __exit__(self, *args: Any) -> None:
        self.client.__exit__(*args)

